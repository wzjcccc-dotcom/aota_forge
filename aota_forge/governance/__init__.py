"""AF Project Governance Subsystem — bounded package surface.

M1/W3: Project Governance Store (``project_store`` / ``sqlite_store``).
M2/W1: Governance Cards (``cards``), the narrow Governance Projection Engine
(``projection``), and generated MAP/STATUS views (``generated_views``).
M2/W2: the bounded Governance Context Route (``context_route``) and the
ephemeral active semantic Working Set + retrieval policy (``working_set``).
M2/W4: the durable bounded CrossProjectGrant (``cross_project_grant``) and
the authorized evidence projection over existing evidence owners
(``evidence_projection``).

This package intentionally contains no execution-state, coordinator-state,
work-progression, or Human Brake storage.  Cross-cutting runtime wiring is W4;
this package is consumed through ``aota_forge.composition.project_governance``.
"""

